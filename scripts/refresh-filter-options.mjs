import { writeFile } from 'node:fs/promises';
import { CATALOG, SITE_ORIGINS, catalogRead, listItems } from '../src/catalog.mjs';

const keys = ['ModelType', 'ActiveBaseModel', 'BaseModel'];
const origins = await Promise.all(SITE_ORIGINS.map(origin => catalogRead(origin, CATALOG.enums)));
const data = origins[0].data;
for (const key of keys) {
  const list = data[key];
  if (!Array.isArray(list) || !list.length || list.some(value => typeof value !== 'string' || !value.trim()) ||
      JSON.stringify(list) !== JSON.stringify(origins[1].data[key])) {
    throw new Error('Both Civitai hosts must return the same valid ' + key + ' enum before refreshing the snapshot.');
  }
}

// Civitai's Models page passes the selected category name as a tag filter. The
// public tag API confirms these common choices and supplies additional names in the app.
const categoryNames = ['character', 'style', 'concept', 'clothing', 'base model', 'poses', 'background', 'tool',
  'buildings', 'vehicle', 'objects', 'animal', 'action', 'assets', 'celebrity'];
const tagNames = [];
for (let i = 0; i < categoryNames.length; i += 4) {
  const group = await Promise.all(categoryNames.slice(i, i + 4).map(async query => {
    const { data } = await catalogRead(SITE_ORIGINS[0], CATALOG.tags, { query, limit: 20 });
    return listItems(data).find(item => item?.name?.toLowerCase() === query)?.name;
  }));
  tagNames.push(...group.filter(Boolean));
}

const snapshot = {
  capturedAt: new Date().toISOString(),
  sources: SITE_ORIGINS.map(origin => origin + CATALOG.enums),
  tagSource: SITE_ORIGINS[0] + CATALOG.tags,
  modelTypes: data.ModelType,
  activeBaseModels: data.ActiveBaseModel,
  baseModels: [...new Set([...data.ActiveBaseModel, ...data.BaseModel])],
  categoryTags: tagNames,
};
const output = '// Generated by scripts/refresh-filter-options.mjs from the public Civitai API.\n' +
  'export const filterOptions = ' + JSON.stringify(snapshot, null, 2) + ';\n';
await writeFile(new URL('../src/filter-options.mjs', import.meta.url), output);
console.log('Loaded ' + snapshot.modelTypes.length + ' model types, ' + snapshot.baseModels.length + ' base models, and ' +
  snapshot.categoryTags.length + ' category tags.');
